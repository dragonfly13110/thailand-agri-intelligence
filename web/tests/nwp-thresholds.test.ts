/**
 * Parity test for the bundled NWP thresholds (lane D / integration).
 *
 * The Cloudflare worker runtime has no file system, so `web/lib/hub/nwp-data.ts`
 * falls back to the copy bundled in `web/lib/hub/nwp-thresholds.ts`. That copy
 * must stay identical to the canonical `config/nwp_thresholds.json`, otherwise
 * production would classify risk levels with numbers the repository does not
 * describe.
 *
 * The runner uses `node --experimental-strip-types`, so the same
 * resolution/transpilation hooks as `nwp-contract.test.ts` are installed
 * locally. No production file is modified.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { registerHooks, stripTypeScriptTypes } from 'node:module';

registerHooks({
  resolve(specifier, context, nextResolve) {
    if (specifier === 'server-only') {
      return { url: 'data:text/javascript,export default undefined;', shortCircuit: true };
    }
    try {
      return nextResolve(specifier, context);
    } catch (error) {
      if (specifier.startsWith('.') || specifier.startsWith('/')) {
        for (const suffix of ['.ts', '/index.ts']) {
          try {
            return nextResolve(specifier + suffix, context);
          } catch {
            // try the next candidate before rethrowing the original error
          }
        }
      }
      throw error;
    }
  },
  load(url, context, nextLoad) {
    if (url.endsWith('.ts') && !url.includes('/node_modules/')) {
      const source = readFileSync(new URL(url), 'utf8');
      return {
        format: 'module',
        source: stripTypeScriptTypes(source, { mode: 'transform' }),
        shortCircuit: true,
      };
    }
    return nextLoad(url, context);
  },
});

const bundled = await import('../lib/hub/nwp-thresholds.ts');
const risk = await import('../lib/hub/nwp-risk.ts');

const canonicalPath = fileURLToPath(
  new URL('../../config/nwp_thresholds.json', import.meta.url),
);
const canonical = JSON.parse(readFileSync(canonicalPath, 'utf8'));

test('bundled thresholds are identical to config/nwp_thresholds.json', () => {
  assert.deepEqual(bundled.BUNDLED_NWP_THRESHOLDS, canonical);
});

test('the generated web/data copy is identical to config/nwp_thresholds.json', () => {
  const generatedPath = fileURLToPath(
    new URL('../data/nwp-thresholds.json', import.meta.url),
  );
  let generated: string;
  try {
    generated = readFileSync(generatedPath, 'utf8');
  } catch {
    // The copy is generated by `scripts/prepare-data.mjs` at build time; a
    // checkout without a build simply has no file to drift.
    return;
  }
  assert.deepEqual(JSON.parse(generated), canonical);
});

test('bundled thresholds pass the fail-closed validator', () => {
  const validated = risk.validateThresholds(bundled.BUNDLED_NWP_THRESHOLDS);
  assert.equal(validated.version, 1);
  for (const [variable, thresholds] of Object.entries(validated.variables)) {
    assert.ok(
      thresholds.watch < thresholds.high && thresholds.high < thresholds.severe,
      `${variable} thresholds must ascend`,
    );
  }
});
