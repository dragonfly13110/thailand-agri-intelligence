function isConnectivityFailure(error: unknown): boolean {
  const message = error instanceof Error ? error.message : String(error);
  const name = error instanceof Error ? error.name : '';
  if (name === 'AbortError' || name === 'TimeoutError') return true;
  if (message.includes('fetch failed')) return true;
  if (message.includes('ECONNREFUSED') || message.includes('ENOTFOUND') || message.includes('ETIMEDOUT')) return true;
  if (message.includes('socket hang up') || message.includes('network')) return true;
  if (/status:?\s*5\d\d/i.test(message)) return true;
  if (message.includes('no such table')) return true;
  return false;
}

/** Create a prepared-statement runner on top of the central D1 database. */
export async function createD1Runner(): Promise<NwpSqlRunner> {
  let d1: Awaited<ReturnType<typeof getD1>>;
  try {
    d1 = await getD1();
  } catch {
    throw new HubDatabaseError('HUB_DATABASE_NOT_CONFIGURED');
  }
  if (!d1) throw new HubDatabaseError('HUB_DATABASE_NOT_CONFIGURED');

  return async (sql: string, params: unknown[]) => {
    try {
      const result = await d1.prepare(sql).bind(...params).all<Record<string, unknown>>();
      return result.results ?? [];
    } catch (error) {
      if (isConnectivityFailure(error)) {
        throw new HubDatabaseError('HUB_DATABASE_NOT_CONFIGURED');
      }
      throw error;
    }
  };
}

