/**
 * Parse the stored bbox. Returns `null` when the payload cannot be trusted;
 * the caller then falls back to the fixed dataset-v1 geometry.
 */
export function parseBbox(raw: unknown): NwpBbox | null {
  const parsed = parseJson(raw);
  if (!Array.isArray(parsed) || parsed.length !== 4) return null;
  const values: number[] = [];
  for (const item of parsed) {
    if (typeof item !== 'number' || !Number.isFinite(item)) return null;
    values.push(item);
  }
  return values as NwpBbox;
}

/**
 * Map one stored snapshot row into the published `NwpGridResponse`.
 *
 * `mean` / `max` must be exactly `nx * ny` long and keep `null` for blocks
 * without source cells. A length mismatch is a broken payload, never a
 * shortened array: it raises `500 NWP_PAYLOAD_INVALID`.
 */
export function mapSnapshotRow(row: NwpSnapshotRow, query: NwpQuery): NwpGridResponse {
  const nx = numberOrNull(row.nx);
  const ny = numberOrNull(row.ny);
  if (nx === null || ny === null || nx <= 0 || ny <= 0) {
    throw new HubRequestError(500, 'NWP_PAYLOAD_INVALID', 'โครงสร้างข้อมูลกริดพยากรณ์ไม่ถูกต้อง');
  }

  const mean = parseNumberArray(row.meanJson);
  const max = parseNumberArray(row.maxJson);
  const expected = nx * ny;

  if (mean.length !== expected || max.length !== expected) {
    // Server-side reason only: the raw arrays never enter the response.
    console.error('[nwp] grid payload length mismatch', {
      runId: row.runId,
      variable: row.variable,
      validAt: row.validAt,
      meanLength: mean.length,
      maxLength: max.length,
      expected,
    });
    throw new HubRequestError(
      500,
      'NWP_PAYLOAD_INVALID',
      'โครงสร้างข้อมูลกริดพยากรณ์ไม่ถูกต้อง กรุณาลองใหม่ภายหลัง',
    );
  }

  if (expected !== NWP_GRID_CELLS) {
    console.error('[nwp] stored grid geometry differs from the published contract', {
      runId: row.runId,
      variable: row.variable,
      nx,
      ny,
      expected: NWP_GRID_CELLS,
    });
  }

  const bbox = parseBbox(row.bboxJson) ?? (NWP_GRID.bbox as NwpBbox);

  return {
    runId: row.runId,
    variable: query.variable,
    validAt: query.validAt,
    bbox,
    nx,
    ny,
    mean,
    max,
    // Units are still pending official confirmation from TMD.
    unit: null,
    method: NWP_METHOD_GRID,
  };
}

/**
 * Fail closed when a serialized grid payload would exceed the 250 KB ceiling.
 */
export function assertGridPayloadSize(payload: unknown): void {
  const serialized = JSON.stringify(payload ?? null);
  const size = byteLength(serialized);
  if (size > NWP_MAX_PAYLOAD_BYTES) {
    console.error('[nwp] grid payload too large', { bytes: size, limit: NWP_MAX_PAYLOAD_BYTES });
    throw new HubRequestError(
      500,
      'NWP_PAYLOAD_TOO_LARGE',
      'ข้อมูลกริดพยากรณ์มีขนาดเกินกำหนด (250 KB)',
    );
  }
}

