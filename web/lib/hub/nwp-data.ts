/**
 * Per-province cell counts carried by `nwp_snapshots.quality_json`.
 * The hub table has no `cell_count` column yet, so the snapshot quality
 * document is the only place a per-province count can live.
 */
export function extractQualityCellCounts(qualityJson: string | null | undefined): Record<string, number> {
  const parsed = parseJson(qualityJson);
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) return {};
  const document = parsed as Record<string, unknown>;
  for (const key of ['provinceCellCounts', 'province_cell_counts', 'cellCounts', 'cell_counts']) {
    const candidate = document[key];
    if (!candidate || typeof candidate !== 'object' || Array.isArray(candidate)) continue;
    const counts: Record<string, number> = {};
    for (const [provinceCode, count] of Object.entries(candidate as Record<string, unknown>)) {
      const value = numberOrNull(count);
      if (value !== null) counts[provinceCode] = value;
    }
    if (Object.keys(counts).length) return counts;
  }
  return {};
}

export type MapProvinceRowsOptions = {
  variable: NwpVariable;
  /** Internal TADIH thresholds; `null` when the thresholds file is unavailable. */
  thresholds: NwpThresholds | null;
  /** Per-province cell counts from the snapshot quality document. */
  qualityCellCounts?: Record<string, number>;
};

/**
 * Map stored province rows into the published `NwpProvinceRow` shape.
 *
 * `riskLevel` is recomputed with `evaluateRisk` from the internal thresholds;
 * a missing value keeps `null` (unknown), never `normal`. When the internal
 * thresholds cannot be loaded the risk level stays `null` as well — a guessed
 * threshold is never published.
 */
export function mapProvinceRows(
  rows: NwpProvinceValueRow[],
  options: MapProvinceRowsOptions,
): NwpProvinceRow[] {
  const { variable, thresholds, qualityCellCounts } = options;
  return rows.map((row) => {
    const value = numberOrNull(row.value);
    const riskLevel = thresholds ? evaluateRisk(value, variable, thresholds) : null;
    const cellCount = numberOrNull(row.cellCount ?? qualityCellCounts?.[row.provinceCode]) ?? 0;
    return {
      provinceCode: row.provinceCode,
      provinceName: row.provinceName,
      value,
      riskLevel,
      distanceKm: numberOrNull(row.distanceKm),
      cellCount,
    };
  });
}

