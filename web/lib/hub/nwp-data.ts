let cachedThresholds: NwpThresholds | null | undefined;
let injectedThresholds: NwpThresholds | null | undefined;

/**
 * Test seam: the offline web test harness has no D1 and no generated data
 * file, so it injects its own thresholds. Production code never calls this;
 * `undefined` restores the file-backed loader.
 */
export function setNwpThresholdsForTests(value: NwpThresholds | null | undefined): void {
  injectedThresholds = value;
  cachedThresholds = undefined;
}

/**
 * Load the public copy of the internal thresholds. Returns `null` when the
 * file is missing or invalid — the caller then publishes `riskLevel: null`
 * instead of a guessed threshold.
 */
export async function getNwpThresholds(): Promise<NwpThresholds | null> {
  if (injectedThresholds !== undefined) return injectedThresholds;
  if (cachedThresholds !== undefined) return cachedThresholds;
  cachedThresholds = await loadThresholdsFromDisk();
  return cachedThresholds;
}

async function loadThresholdsFromDisk(): Promise<NwpThresholds | null> {
  // The public copy lives in `web/data/` (generated by `scripts/prepare-data.mjs`).
  // The other candidates only matter when the process runs from the repository
  // root; a worker runtime without a file system simply has no thresholds.
  const candidates = [
    join(process.cwd(), NWP_THRESHOLDS_FILE),
    join(process.cwd(), 'web', NWP_THRESHOLDS_FILE),
    join(process.cwd(), 'config', 'nwp_thresholds.json'),
  ];
  for (const candidate of candidates) {
    try {
      const raw = await readFile(candidate, 'utf8');
      return validateThresholds(JSON.parse(raw));
    } catch {
      // Try the next candidate; a missing or malformed file fails closed.
    }
  }
  // No file system (Cloudflare worker): fall back to the bundled copy, which
  // is asserted to be identical to `config/nwp_thresholds.json` by the test
  // suite. Without it every risk level would be `null` in production.
  try {
    return validateThresholds(BUNDLED_NWP_THRESHOLDS);
  } catch {
    return null;
  }
}

