export function toRunRow(raw: Record<string, unknown>): NwpRunRow {
  return {
    runId: String(raw.runId ?? ''),
    sourceId: text(raw.sourceId),
    domain: text(raw.domain),
    initAt: text(raw.initAt),
    retrievedAt: text(raw.retrievedAt),
    // Current registry approval supersedes the stale status stored with older runs.
    licenseStatus: NWP_RESOURCE_LICENSE.license_status,
    unitStatus: text(raw.unitStatus),
    publicationMode: text(raw.publicationMode),
    variablesJson: text(raw.variablesJson),
    leadHoursJson: text(raw.leadHoursJson),
    gridJson: text(raw.gridJson),
    status: text(raw.status),
    createdAt: text(raw.createdAt),
  };
}

/**
 * Derive the lead hours of every variable from the stored `valid_at` values
 * relative to `initAt`. Upstream files have heterogeneous time axes (a daily
 * variable has ~3 columns while an hourly variable has ~72), so the per
 * variable axis cannot be assumed.
 */
export function deriveLeadHoursByVariable(
  initAt: string | null,
  snapshots: Array<{ variable: string; validAt: string }>,
): Record<string, number[]> {
  const initMs = parseStoredInstant(initAt);
  const leads: Record<string, number[]> = {};
  if (initMs === null) return leads;

  for (const snapshot of snapshots) {
    const validMs = parseStoredInstant(snapshot.validAt);
    if (validMs === null) continue;
    const lead = Math.round((validMs - initMs) / 3_600_000);
    if (!Number.isFinite(lead)) continue;
    (leads[snapshot.variable] ??= []).push(lead);
  }

  for (const variable of Object.keys(leads)) {
    leads[variable] = [...new Set(leads[variable])].sort((a, b) => a - b);
  }
  return leads;
}

/** Map one stored run row into the published `NwpRun` shape. */
export function mapRunRow(row: NwpRunRow, leadHoursByVariable: Record<string, number[]>): NwpRunWithLeads {
  const storedVariables = parseStringArray(row.variablesJson).filter(isNwpVariable);
  const variables = storedVariables.length
    ? storedVariables
    : Object.keys(leadHoursByVariable).filter(isNwpVariable);

  const derivedLeads = Object.values(leadHoursByVariable).flat();
  const storedLeads = parsePlainNumberArray(row.leadHoursJson);
  const leadHours = [...new Set(derivedLeads.length ? derivedLeads : storedLeads)].sort((a, b) => a - b);

  return {
    runId: row.runId,
    initAt: row.initAt ?? '',
    retrievedAt: row.retrievedAt ?? '',
    domain: row.domain ?? NWP_DOMAIN,
    domainLabel: row.domain === NWP_DOMAIN ? NWP_DOMAIN_LABEL : (row.domain ?? NWP_DOMAIN_LABEL),
    variables,
    leadHours,
    status: (row.status ?? 'failed') as NwpRunStatus,
    licenseStatus: row.licenseStatus ?? 'pending',
    unitStatus: row.unitStatus ?? 'pending_official_confirmation',
    publicationMode: (row.publicationMode ?? 'metadata_only') as NwpPublicationMode,
    leadHoursByVariable,
  };
}

