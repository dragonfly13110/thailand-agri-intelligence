/**
 * A run is readable only after the publisher finished it (`ready`/`partial`).
 * A failed run keeps the child rows written before the failure, so the status
 * must be rejected before any snapshot is served; an unknown/null status is
 * unpublished as well. `403` is reserved for the metadata-only kill switch.
 */
function assertPublishable(run: NwpRunRow): void {
  if (run.status !== 'ready' && run.status !== 'partial') {
    throw new HubRequestError(
      404,
      'NWP_NOT_FOUND',
      'ไม่พบรอบพยากรณ์ที่เผยแพร่แล้ว',
    );
  }
  if (run.publicationMode === 'metadata_only') {
    throw new HubRequestError(
      403,
      'NWP_PUBLICATION_DISABLED',
      'การเผยแพร่ตัวเลขพยากรณ์ถูกปิดไว้ชั่วคราว (metadata_only)',
    );
  }
}

function runWarnings(extra: string[] = []): string[] {
  return [...NWP_WARNINGS, ...extra];
}

/**
 * `GET /api/v1/nwp/runs` — the usable forecast runs, newest first.
 */
export async function readNwpRuns(runner: NwpSqlRunner): Promise<NwpPayload<NwpRunWithLeads[]>> {
  const rows = await runner(
    'SELECT ' + RUN_COLUMNS + " FROM nwp_runs WHERE status IN ('ready','partial') ORDER BY init_at DESC LIMIT ?",
    [NWP_RUNS_LIMIT],
  );
  const runRows = rows.map(toRunRow);

  const snapshotRows: Array<{ runId: string; variable: string; validAt: string }> = [];
  if (runRows.length) {
    // Placeholders are built from the row count only; every value is bound.
    const placeholders = runRows.map(() => '?').join(',');
    const snapshots = await runner(
      'SELECT run_id AS runId, variable, valid_at AS validAt FROM nwp_snapshots WHERE run_id IN (' +
        placeholders + ')',
      runRows.map((row) => row.runId),
    );
    for (const snapshot of snapshots) {
      snapshotRows.push({
        runId: String(snapshot.runId ?? ''),
        variable: String(snapshot.variable ?? ''),
        validAt: String(snapshot.validAt ?? ''),
      });
    }
  }

  const runs = runRows.map((row) => {
    const own = snapshotRows.filter((snapshot) => snapshot.runId === row.runId);
    return mapRunRow(row, deriveLeadHoursByVariable(row.initAt, own));
  });

  return {
    data: runs,
    meta: {
      availability: runs.length ? 'ready' : 'empty',
      completeness: runs.some((run) => run.status === 'partial') ? 'partial' : runs.length ? 'complete' : 'unknown',
      access: resolveAccessStatus(NWP_RESOURCE_LICENSE.license_status),
      sourceIds: [NWP_SOURCE_ID],
      dataAsOf: runs.length ? runs[0].initAt : null,
      datasetVersion: NWP_DATASET_VERSION,
      warnings: runWarnings(),
      runtimeMode: 'database',
    },
  };
}

/**
 * `GET /api/v1/nwp/grid` — one downsampled forecast grid.
 */
export async function readNwpGrid(
  query: NwpQuery,
  runner: NwpSqlRunner,
): Promise<NwpPayload<NwpGridResponse>> {
  const run = await readRunRow(runner, query.runId);
  if (!run) {
    throw new HubRequestError(404, 'NWP_NOT_FOUND', 'ไม่พบรอบพยากรณ์ที่ระบุ');
  }
  assertPublishable(run);

  const snapshot = await readSnapshotRow(runner, query);
  if (!snapshot) {
    throw new HubRequestError(404, 'NWP_NOT_FOUND', 'ไม่พบข้อมูลกริดพยากรณ์ที่ระบุ');
  }

  const grid = mapSnapshotRow(snapshot, query);
  grid.unit = isNwpUnitConfirmed(run.unitStatus) ? snapshot.unit : null;
  assertGridPayloadSize(grid);

  return {
    data: grid,
    meta: {
      availability: 'ready',
      completeness: run.status === 'partial' ? 'partial' : 'complete',
      access: resolveAccessStatus(run.licenseStatus),
      sourceIds: [NWP_SOURCE_ID],
      dataAsOf: grid.validAt,
      datasetVersion: NWP_DATASET_VERSION,
      warnings: runWarnings(),
      runtimeMode: 'database',
    },
  };
}

/**
 * `GET /api/v1/nwp/provinces` — the provincial watchlist of one forecast step.
 */
export async function readNwpProvinces(
  query: NwpQuery,
  runner: NwpSqlRunner,
  thresholds: NwpThresholds | null,
): Promise<NwpPayload<NwpProvincesResponse>> {
  const run = await readRunRow(runner, query.runId);
  if (!run) {
    throw new HubRequestError(404, 'NWP_NOT_FOUND', 'ไม่พบรอบพยากรณ์ที่ระบุ');
  }
  assertPublishable(run);

  const snapshotRows = await runner(
    'SELECT run_id AS runId, variable, valid_at AS validAt, unit, quality_json AS qualityJson FROM nwp_snapshots ' +
      'WHERE run_id = ? AND variable = ? AND ' + VALID_AT_MATCH + ' LIMIT 1',
    [query.runId, query.variable, validAtKey(query.validAt)],
  );
  const snapshot = snapshotRows[0];
  if (!snapshot) {
    throw new HubRequestError(404, 'NWP_NOT_FOUND', 'ไม่พบข้อมูลกริดพยากรณ์ที่ระบุ');
  }

  const cellCountExists = await hasCellCountColumn(runner);
  const provinceRows = await runner(
    'SELECT ' + PROVINCE_COLUMNS + (cellCountExists ? ', cell_count AS cellCount' : '') +
      ' FROM nwp_province_values WHERE run_id = ? AND variable = ? AND ' + VALID_AT_MATCH +
      ' ORDER BY province_code',
    [query.runId, query.variable, validAtKey(query.validAt)],
  );

  const qualityCellCounts = extractQualityCellCounts(text(snapshot.qualityJson));
  const rows: NwpProvinceValueRow[] = provinceRows.map((row) => ({
    runId: String(row.runId ?? query.runId),
    variable: String(row.variable ?? query.variable),
    validAt: String(row.validAt ?? query.validAt),
    provinceCode: String(row.provinceCode ?? ''),
    provinceName: String(row.provinceName ?? ''),
    value: numberOrNull(row.value),
    method: text(row.method),
    radiusKm: numberOrNull(row.radiusKm),
    distanceKm: numberOrNull(row.distanceKm),
    // The stored level is kept for traceability only; the published level is
    // always recomputed from the internal thresholds.
    riskLevel: text(row.riskLevel),
    cellCount: numberOrNull(row.cellCount),
  }));

  const provinces = mapProvinceRows(rows, {
    variable: query.variable,
    thresholds: isNwpUnitConfirmed(run.unitStatus) ? thresholds : null,
    qualityCellCounts,
  });
  const warnings = runWarnings();
  if (!cellCountExists && !Object.keys(qualityCellCounts).length) {
    warnings.push(
      'จำนวนเซลล์ที่ใช้คำนวณรายจังหวัดยังไม่ถูกบันทึกในคลังข้อมูล (cell_count) ค่า 0 ไม่ได้หมายความว่าไม่มีเซลล์ในรัศมี',
    );
  }

  return {
    data: {
      runId: query.runId,
      variable: query.variable,
      validAt: query.validAt,
      unit: isNwpUnitConfirmed(run.unitStatus) ? text(snapshot.unit) : null,
      method: NWP_METHOD_PROVINCE,
      radiusKm: NWP_PROVINCE_RADIUS_KM,
      provinces,
    },
    meta: {
      availability: provinces.length ? 'ready' : 'empty',
      completeness: run.status === 'partial' ? 'partial' : provinces.length ? 'complete' : 'unknown',
      access: resolveAccessStatus(run.licenseStatus),
      sourceIds: [NWP_SOURCE_ID],
      dataAsOf: query.validAt,
      datasetVersion: NWP_DATASET_VERSION,
      warnings,
      runtimeMode: 'database',
    },
  };
}
