  'province_name AS provinceName, value, method, radius_km AS radiusKm, distance_km AS distanceKm, ' +
  'risk_level AS riskLevel';

async function readRunRow(runner: NwpSqlRunner, runId: string): Promise<NwpRunRow | null> {
  const rows = await runner(
    'SELECT ' + RUN_COLUMNS + ' FROM nwp_runs WHERE run_id = ? LIMIT 1',
    [runId],
  );
  const row = rows[0];
  return row ? toRunRow(row) : null;
}

async function readSnapshotRow(runner: NwpSqlRunner, query: NwpQuery): Promise<NwpSnapshotRow | null> {
  const rows = await runner(
    'SELECT ' + SNAPSHOT_COLUMNS + ' FROM nwp_snapshots WHERE run_id = ? AND variable = ? AND ' +
      VALID_AT_MATCH + ' LIMIT 1',
    [query.runId, query.variable, validAtKey(query.validAt)],
  );
  const row = rows[0];
  if (!row) return null;
  return {
    runId: String(row.runId ?? query.runId),
    variable: String(row.variable ?? query.variable),
    validAt: String(row.validAt ?? query.validAt),
    unit: text(row.unit),
    bboxJson: text(row.bboxJson),
    nx: numberOrNull(row.nx),
    ny: numberOrNull(row.ny),
    meanJson: text(row.meanJson),
    maxJson: text(row.maxJson),
    qualityJson: text(row.qualityJson),
  };
}

let cellCountColumn: boolean | undefined;

/**
 * The hub table `nwp_province_values` has no `cell_count` column in the
 * current DDL. The column list is probed once per process so the endpoint
 * keeps working while the DDL is completed, and picks the column up as soon
 * as it exists.
 */
async function hasCellCountColumn(runner: NwpSqlRunner): Promise<boolean> {
  if (cellCountColumn !== undefined) return cellCountColumn;
  try {
    const rows = await runner('PRAGMA table_info(nwp_province_values)', []);
    cellCountColumn = rows.some((row) => String(row.name ?? '').toLowerCase() === 'cell_count');
  } catch {
    cellCountColumn = false;
  }
  return cellCountColumn;
}

