/**
 * TMD HPC NWP read model (lane D) — server only.
 *
 * Reads the `nwp_runs` / `nwp_snapshots` / `nwp_province_values` tables of the
 * central D1 hub and turns them into the published NWP API payloads
 * (`/api/v1/nwp/runs`, `/api/v1/nwp/grid`, `/api/v1/nwp/provinces`).
 *
 * Governance rules that this module must never break:
 * - Every number is a MODEL FORECAST, never an observation, and is never
 *   written into the `observations` table.
 * - `unit` stays `null` until TMD confirms units in writing
 *   (`NWP_VARIABLE_UNITS_PENDING` in `./nwp-types`).
 * - Missing stays `null`: a block without source cells is `null`, never `0`,
 *   and never interpolated.
 * - A grid cell is not a province value. The province number is the maximum
 *   block maximum inside 25 km of the province reference point
 *   (`max_within_25km`), never a provincial average.
 * - The 77 province codes are a registry, not a coverage claim.
 *
 * The module is split into pure helpers (validation, mapping, risk mapping)
 * that are unit-testable without a D1 client, and thin readers that take an
 * injected `NwpSqlRunner`.
 */

