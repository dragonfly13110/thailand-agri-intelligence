// คำนวณ Farm-to-Storage Connectivity Score รายจังหวัดสำหรับทั้ง 77 จังหวัด
export function generateProvinceConnectivityScores(): ProvinceConnectivity[] {
  // ดึงข้อมูลรวมต่อจังหวัดจาก Facilities
  const facilityStatsByProvince = new Map<
    string,
    {
      count: number;
      totalCapacity: number;
      siloCapacity: number;
      coldStorageCapacity: number;
      warehouseCapacity: number;
      scores: number[];
      distances: number[];
    }
  >();

  for (const fac of FACILITIES_DATA) {
    let stat = facilityStatsByProvince.get(fac.provinceCode);
    if (!stat) {
      stat = {
        count: 0,
        totalCapacity: 0,
        siloCapacity: 0,
        coldStorageCapacity: 0,
        warehouseCapacity: 0,
        scores: [],
        distances: [],
      };
      facilityStatsByProvince.set(fac.provinceCode, stat);
    }
    stat.count += 1;
    stat.totalCapacity += fac.capacityTons;
    if (fac.type === 'silo') stat.siloCapacity += fac.capacityTons;
    if (fac.type === 'cold_storage') stat.coldStorageCapacity += fac.capacityTons;
    if (fac.type === 'general_warehouse') stat.warehouseCapacity += fac.capacityTons;
    stat.scores.push(fac.farmConnectivityScore);
    stat.distances.push(fac.avgFarmDistanceKm);
  }

  // พืชเศรษฐกิจหลักตามลักษณะภาค/พื้นที่
  const getDominantCrop = (province: { code: string; name: string; region: string }) => {
    if (['14', '72', '18', '60', '66', '15', '17'].includes(province.code)) return 'ข้าวนาปี / ข้าวนาปรัง';
    if (['45', '32', '34', '35', '31', '33', '37', '44', '56'].includes(province.code)) return 'ข้าวหอมมะลิ (GI)';
    if (['22', '21', '86', '95', '50', '51', '70', '73', '53', '57'].includes(province.code)) return 'ผลไม้เศรษฐกิจ (ทุเรียน, มังคุด, ส้ม, ลำไย)';
    if (['84', '80', '81', '92', '90', '94', '41', '38'].includes(province.code)) return 'ยางพาราและปาล์มน้ำมัน';
    if (['30', '16', '65', '62', '71', '36', '54', '40'].includes(province.code)) return 'ข้าวโพดเลี้ยงสัตว์และมันสำปะหลัง';
    if (['74', '11', '85', '90', '83'].includes(province.code)) return 'สัตว์น้ำและอาหารแปรรูปแช่เยือกแข็ง';
    return 'พืชไร่และข้าวผสมผสาน';
  };

  return THAILAND_PROVINCES.map((prov) => {
    const stat = facilityStatsByProvince.get(prov.code);
    const dominantCrop = getDominantCrop(prov);

    let connectivityScore: number;
    let avgFarmDistanceKm: number;
    let facilityCount = 0;
    let totalCapacityTons = 0;
    let siloCapacityTons = 0;
    let coldStorageCapacityTons = 0;
    let warehouseCapacityTons = 0;

    if (stat && stat.count > 0) {
      facilityCount = stat.count;
      totalCapacityTons = stat.totalCapacity;
      siloCapacityTons = stat.siloCapacity;
      coldStorageCapacityTons = stat.coldStorageCapacity;
      warehouseCapacityTons = stat.warehouseCapacity;
      connectivityScore = Math.round(stat.scores.reduce((a, b) => a + b, 0) / stat.scores.length);
      avgFarmDistanceKm = Number((stat.distances.reduce((a, b) => a + b, 0) / stat.distances.length).toFixed(1));
    } else {
      // จังหวัดที่ยังไม่มีคลังขนาดใหญ่ในโมเดล ให้คำนวณตามลักษณะภูมิภาคและโครงข่ายถนน
      const codeNum = Number(prov.code) || 50;
      if (prov.region === 'ภาคกลาง') {
        avgFarmDistanceKm = Number((18 + (codeNum % 8) * 1.5).toFixed(1));
        connectivityScore = Math.round(85 - (codeNum % 7));
      } else if (prov.region === 'ภาคตะวันออก' || prov.region === 'ภาคตะวันตก') {
        avgFarmDistanceKm = Number((22 + (codeNum % 10) * 1.6).toFixed(1));
        connectivityScore = Math.round(80 - (codeNum % 9));
      } else if (prov.region === 'ภาคตะวันออกเฉียงเหนือ') {
        avgFarmDistanceKm = Number((24 + (codeNum % 12) * 1.8).toFixed(1));
        connectivityScore = Math.round(78 - (codeNum % 11));
      } else if (prov.region === 'ภาคเหนือ') {
        avgFarmDistanceKm = Number((28 + (codeNum % 14) * 2.1).toFixed(1));
        connectivityScore = Math.round(72 - (codeNum % 13));
      } else {
        avgFarmDistanceKm = Number((25 + (codeNum % 10) * 2.0).toFixed(1));
        connectivityScore = Math.round(76 - (codeNum % 10));
      }
    }

    const grade: 'high' | 'moderate' | 'low' =
      connectivityScore >= 80 ? 'high' : connectivityScore >= 65 ? 'moderate' : 'low';

    const gradeLabel =
      grade === 'high'
        ? 'เข้าถึงสะดวก (High)'
        : grade === 'moderate'
        ? 'ปานกลาง (Moderate)'
        : 'ห่างไกล / ขาดแคลนจุดรวบรวม (Low)';

    const bottleneckRisk: 'low' | 'moderate' | 'high' =
      connectivityScore >= 80 ? 'low' : connectivityScore >= 65 ? 'moderate' : 'high';

    let recommendation = 'รักษามาตรฐานการเชื่อมโยงและบริหารจัดการคิวขนส่ง';
    if (grade === 'low') {
      recommendation = 'ควรเร่งจัดตั้งศูนย์รวบรวมผลผลิตระดับอำเภอหรือจุดลดความชื้นชุมชน';
    } else if (grade === 'moderate') {
      recommendation = 'เสริมความจุคลังควบคุมอุณหภูมิรองรับผลผลิตช่วงฤดูกาลเก็บเกี่ยวสูงสุด (Peak)';
    }

    return {
      provinceCode: prov.code,
      provinceName: prov.name,
      region: prov.region,
      connectivityScore,
      avgFarmDistanceKm,
      grade,
      gradeLabel,
      facilityCount,
      totalCapacityTons,
      siloCapacityTons,
      coldStorageCapacityTons,
      warehouseCapacityTons,
      dominantCommodity: dominantCrop,
      bottleneckRisk,
      recommendation,
    };
  }).sort((a, b) => b.connectivityScore - a.connectivityScore);
}

// คำนวณภาพรวมสถิติทั้งประเทศ
export function calculateLogisticsSummary(facilities: Facility[]): LogisticsSummary {
  const totalFacilities = facilities.length;
  let totalCapacityTons = 0;
  let totalUtilizedTons = 0;
  let siloFacilitiesCount = 0;
  let siloCapacityTons = 0;
  let coldStorageFacilitiesCount = 0;
  let coldStorageCapacityTons = 0;
  let warehouseFacilitiesCount = 0;
  let warehouseCapacityTons = 0;
  let operationalCount = 0;
  let maintenanceCount = 0;
  let fullCount = 0;
  let totalConnectivity = 0;
  let totalDistance = 0;

  for (const f of facilities) {
    totalCapacityTons += f.capacityTons;
    totalUtilizedTons += f.utilizedTons;
    totalConnectivity += f.farmConnectivityScore;
    totalDistance += f.avgFarmDistanceKm;

    if (f.type === 'silo') {
      siloFacilitiesCount += 1;
      siloCapacityTons += f.capacityTons;
    } else if (f.type === 'cold_storage') {
      coldStorageFacilitiesCount += 1;
      coldStorageCapacityTons += f.capacityTons;
    } else if (f.type === 'general_warehouse') {
      warehouseFacilitiesCount += 1;
      warehouseCapacityTons += f.capacityTons;
    }

    if (f.status === 'operational') operationalCount += 1;
    else if (f.status === 'maintenance') maintenanceCount += 1;
    else if (f.status === 'full') fullCount += 1;
  }

  const overallUtilizationRate =
    totalCapacityTons > 0 ? Number(((totalUtilizedTons / totalCapacityTons) * 100).toFixed(1)) : 0;
  const avgNationalConnectivityScore =
    totalFacilities > 0 ? Number((totalConnectivity / totalFacilities).toFixed(1)) : 0;
  const avgNationalFarmDistanceKm =
    totalFacilities > 0 ? Number((totalDistance / totalFacilities).toFixed(1)) : 0;

  return {
    totalFacilities,
    totalCapacityTons,
    totalUtilizedTons,
    overallUtilizationRate,
    siloFacilitiesCount,
    siloCapacityTons,
    coldStorageFacilitiesCount,
    coldStorageCapacityTons,
    warehouseFacilitiesCount,
    warehouseCapacityTons,
    operationalCount,
    maintenanceCount,
    fullCount,
    avgNationalConnectivityScore,
    avgNationalFarmDistanceKm,
  };
}

// กรองรายการคลังสินค้าตามเงื่อนไข
export function filterFacilities(facilities: Facility[], filters?: LogisticsFilterOptions): Facility[] {
  if (!filters) return facilities;

  return facilities.filter((f) => {
    // กรองรหัสจังหวัด
    if (filters.provinceCode && filters.provinceCode !== 'all' && f.provinceCode !== filters.provinceCode) {
      return false;
    }

    // กรองประเภทคลังสินค้า
    if (filters.facilityType && filters.facilityType !== 'all' && f.type !== filters.facilityType) {
      return false;
    }

    // กรองสถานะ
    if (filters.status && filters.status !== 'all' && f.status !== filters.status) {
      return false;
    }

    // กรองขนาดความจุ
    if (filters.minCapacity !== undefined && f.capacityTons < filters.minCapacity) {
      return false;
    }
    if (filters.maxCapacity !== undefined && f.capacityTons > filters.maxCapacity) {
      return false;
    }

    // กรองช่วงขนาดความจุแบบ tier
    if (filters.capacityTier && filters.capacityTier !== 'all') {
      if (filters.capacityTier === 'small' && f.capacityTons >= 20000) return false;
      if (filters.capacityTier === 'medium' && (f.capacityTons < 20000 || f.capacityTons > 40000)) return false;
      if (filters.capacityTier === 'large' && (f.capacityTons <= 40000 || f.capacityTons > 60000)) return false;
      if (filters.capacityTier === 'mega' && f.capacityTons <= 60000) return false;
    }

    // ค้นหาตามข้อความ
    if (filters.search) {
      const q = filters.search.toLowerCase().trim();
      const matchName = f.name.toLowerCase().includes(q);
      const matchDistrict = f.district.toLowerCase().includes(q);
      const matchProvince = f.provinceName.toLowerCase().includes(q);
      const matchOperator = f.operator.toLowerCase().includes(q);
      const matchCommodity = f.supportedCommodities.some((c) => c.toLowerCase().includes(q));
      if (!matchName && !matchDistrict && !matchProvince && !matchOperator && !matchCommodity) {
        return false;
      }
    }

    return true;
  });
}

// ฟังก์ชันหลักสร้าง Payload สำหรับหน้าจอและ API
export function buildLogisticsDashboard(filters?: LogisticsFilterOptions): LogisticsDashboardPayload {
  const allFacilities = FACILITIES_DATA;
  const filteredFacilities = filterFacilities(allFacilities, filters);
  const nationalSummary = calculateLogisticsSummary(allFacilities);
  const provinceScores = generateProvinceConnectivityScores();

  // คำนวณสรุปเฉพาะส่วนที่ถูกกรอง
  let filteredCapacity = 0;
  let filteredUtilized = 0;
  let filteredConnectivityTotal = 0;

  for (const f of filteredFacilities) {
    filteredCapacity += f.capacityTons;
    filteredUtilized += f.utilizedTons;
    filteredConnectivityTotal += f.farmConnectivityScore;
  }

  const filteredAvgUtilization =
    filteredCapacity > 0 ? Number(((filteredUtilized / filteredCapacity) * 100).toFixed(1)) : 0;
  const filteredAvgConnectivity =
    filteredFacilities.length > 0
      ? Number((filteredConnectivityTotal / filteredFacilities.length).toFixed(1))
      : 0;

  const facilityTypeOptions: FacilityTypeOption[] = Object.values(FACILITY_TYPE_CONFIGS).map((cfg) => ({
    ...cfg,
    count: allFacilities.filter((f) => f.type === cfg.id).length,
  }));

  const statusOptions: FacilityStatusOption[] = Object.values(FACILITY_STATUS_CONFIGS).map((cfg) => ({
    ...cfg,
    count: allFacilities.filter((f) => f.status === cfg.id).length,
  }));

  return {
    sample: true,
    generatedAt: new Date().toISOString(),
    summary: nationalSummary,
    filteredSummary: {
      totalFacilities: filteredFacilities.length,
      totalCapacityTons: filteredCapacity,
      avgUtilizationRate: filteredAvgUtilization,
      avgConnectivityScore: filteredAvgConnectivity,
    },
    facilities: filteredFacilities,
    provinceScores,
    allProvinces: THAILAND_PROVINCES,
    facilityTypes: facilityTypeOptions,
    statuses: statusOptions,
    sources: LOGISTICS_SOURCES,
    warnings: LOGISTICS_WARNINGS,
  };
}
